export function port(value, fallback) {
  const number = Number(value || fallback);
  if (!Number.isInteger(number) || number < 1 || number > 65535) throw Error('Use a network port from 1 to 65535.');
  return number;
}
export function privateIPv4(host) {
  if (!/^\d+\.\d+\.\d+\.\d+$/.test(host)) return false;
  const n = host.split('.').map(Number);
  return n.every(v => v >= 0 && v <= 255) && (n[0] === 10 || n[0] === 192 && n[1] === 168 || n[0] === 172 && n[1] >= 16 && n[1] <= 31);
}
export function settings(backend = {}, wifi = {}, interfaces = networkInterfaces()) {
  const cloud = wifi.CLOUD_API_URL || '';
  if (cloud && !/^https:\/\/[a-z0-9-]+\.supabase\.co\/functions\/v1\/drain-api$/.test(cloud)) throw Error('CLOUD_API_URL must be this project’s HTTPS Supabase drain-api function URL.');
  const addresses = [...new Set(Object.entries(interfaces).filter(([name]) => !/^(utun|tun|docker|veth|bridge)/i.test(name))
    .flatMap(([, values]) => values || []).filter(v => !v.internal && v.family === 'IPv4' && privateIPv4(v.address)).map(v => v.address))];
  const host = wifi.WIFI_HOST || (addresses.length === 1 ? addresses[0] : '');
  if (!cloud && (!host || !privateIPv4(host))) throw Error(`Set WIFI_HOST in device/wifi/.env to this computer's LAN IPv4 address. Candidates: ${addresses.join(', ') || 'none; connect Wi-Fi first'}.`);
  if (!cloud && addresses.length && !addresses.includes(host)) throw Error('WIFI_HOST is not assigned to this computer. Update device/wifi/.env after changing networks.');
  const apiPort = port(backend.PORT, 8000), webPort = port(wifi.WEB_PORT, 3000);
  if (apiPort === webPort) throw Error('Backend and website must use different ports.');
  const flag = name => {
    if (wifi[name] !== undefined && !['true','false'].includes(wifi[name])) throw Error(`${name} must be true or false.`);
    return wifi[name] === 'true';
  };
  return { host, apiPort, webPort, cloud: Boolean(cloud), base: cloud || `http://${host}:${apiPort}`, local: cloud || `http://127.0.0.1:${apiPort}`, web: `http://localhost:${webPort}`,
    ssid: wifi.WIFI_SSID || '', password: wifi.WIFI_PASSWORD || '', allowHttp: flag('ALLOW_LOCAL_HTTP'),
    uart: flag('USE_UART'), initialize: flag('INITIALIZE_EMPTY_FILESYSTEM'), resume: flag('RESUME_AFTER_RESTART') };
}
export function firmwareHeader(config, record, key) {
  if (!config.ssid || config.ssid === 'YOUR_WIFI_NAME' || config.password === 'YOUR_WIFI_PASSWORD') throw Error('Fill WIFI_SSID and WIFI_PASSWORD in device/wifi/.env.');
  if (!config.cloud && !config.allowHttp) throw Error('For this trusted LAN bench test, set ALLOW_LOCAL_HTTP=true in device/wifi/.env.');
  if (config.cloud && !config.rootCa?.includes('-----BEGIN CERTIFICATE-----')) throw Error('Cloud firmware requires the verified Supabase root CA. Run npm run cloud:configure.');
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(record) || !key.startsWith('dk_')) throw Error('Invalid recording or fixture key.');
  const string = value => {
    if (/[\x00-\x1f\x7f]/.test(value)) throw Error('Settings cannot contain control characters.');
    return JSON.stringify(value);
  };
  return '// Generated by wifi:prepare. Private: do not share or commit.\n#pragma once\n'
    + Object.entries({ WIFI_SSID: config.ssid, WIFI_PASSWORD: config.password, API_BASE_URL: config.base, SENSOR_RECORD_ID: record, SENSOR_KEY: key })
      .map(([k,v]) => `constexpr char ${k}[] = ${string(v)};`).join('\n') + '\n'
    + Object.entries({ ALLOW_LOCAL_HTTP: !config.cloud, USE_UART: config.uart, INITIALIZE_EMPTY_FILESYSTEM: config.initialize, RESUME_AFTER_RESTART: config.resume })
      .map(([k,v]) => `constexpr bool ${k} = ${v};`).join('\n')
    + `\nconstexpr char PREVIOUS_API_BASE_URL[] = ${string(config.previousBase || '')};\n`
    + `constexpr char API_ROOT_CA[] = R"PEM(${config.cloud ? config.rootCa : ''})PEM";\n`;
}
export async function api(base, token, path, body, fetcher = fetch) {
  let response;
  try { response = await fetcher(`${base}/api/v1${path}`, { method: body === undefined ? 'GET' : 'POST', redirect: 'error',
    headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }), signal: AbortSignal.timeout(15000) }); }
  catch { throw Error(`Cannot reach ${base}. Start npm run wifi:start and check its displayed ports.`); }
  const value = await response.json();
  if (!response.ok) throw Object.assign(Error(`API ${response.status}: ${value.error?.message || 'request failed'}`), { status: response.status });
  return value;
}
// A recording saved before a migration or cleanup may no longer exist. That is not a failure: the caller starts a new one.
export async function findPreviousRecording(request, base, token, recordId) {
  try { return (await request(base, token, `/records/${recordId}`)).record; }
  catch (error) { if (error.status === 404) return null; throw error; }
}
// Installer-provisioned units are registered without an owner. These two let the installer link one to a customer's account.
export async function findAuthUser(email, { supabaseUrl, key, fetcher = fetch }) {
  const wanted = String(email).trim().toLowerCase();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(wanted)) throw Error('Enter the account e-mail as name@example.com.');
  for (let page = 1; page <= 25; page++) {
    const response = await fetcher(`${supabaseUrl}/auth/v1/admin/users?page=${page}&per_page=200`, { signal: AbortSignal.timeout(10000),
      headers: { apikey: key, ...(key.startsWith('eyJ') ? { Authorization: `Bearer ${key}` } : {}) } });
    if (!response.ok) throw Error('Cannot look up that account. Check the Supabase server key in backend/.env.');
    const { users = [] } = await response.json();
    const match = users.find(user => user.email?.toLowerCase() === wanted);
    if (match) return match;
    if (users.length < 200) return null;
  }
  return null;
}
export async function grantOwner(accessStore, fixture, userId, now = new Date()) {
  const members = await accessStore.list('device_members', { device_id: fixture }, 100);
  if (members.some(member => member.user_id === userId)) return false;
  await accessStore.insert('device_members', { id: randomUUID(), device_id: fixture, user_id: userId, role: 'owner', created_at: now.toISOString() });
  return true;
}
export async function checkTables(config, fetcher = fetch) {
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(config.supabaseUrl) || !config.supabaseKey?.startsWith('sb_secret_')) throw Error('Configure backend/.env with your own Supabase URL and server secret.');
  for (const [table, column] of [['drain_records','record_id'],['dm_devices','device_id'],['dm_device_members','id'],['dm_device_keys','key_hash']]) {
    let response;
    try { response = await fetcher(`${config.supabaseUrl}/rest/v1/${table}?select=${column}&limit=0`, {
      headers: { apikey: config.supabaseKey, Authorization: `Bearer ${config.supabaseKey}` }, signal: AbortSignal.timeout(15000) }); }
    catch { throw Error('Cannot reach Supabase. Check Internet access and backend/.env.'); }
    if (!response.ok) throw Error(`${table}: HTTP ${response.status}. ${response.status === 404 ? `Apply ${table === 'drain_records' ? 'supabase/migrations/202610270001_drain_records.sql' : accessMigration} in Supabase SQL Editor.` : 'Check Supabase server credentials and permissions.'}`);
  }
}
export async function prepareRecord({ config, token, fixture, type, confirmEmpty, previous, request = api }) {
  if (!/^[a-zA-Z0-9_-]{1,64}$/.test(fixture)) throw Error('Fixture ID: use 1–64 letters, digits, dashes or underscores.');
  if (!['monitoring','calibration','drainage'].includes(type)) throw Error('Choose monitoring, calibration or drainage.');
  if (type === 'calibration' && !confirmEmpty) throw Error('With an empty fixture and tap off, add --confirm-empty.');
  const devices = await request(config.local, token, '/devices');
  if (!devices.devices.some(d => d.device_id === fixture)) await request(config.local, token, '/devices', { device_id: fixture, name: fixture });
  const active = await request(config.local, token, `/records?fixture_id=${fixture}&data_source=sensor&recording_status=recording`);
  let record = active.records[0];
  if (record && record.record_type !== type) throw Error(`An active ${record.record_type} exists. Stop the board, then run npm run wifi:finish before changing recording types.`);
  const key = previous?.key || (await request(config.local, token, `/devices/${fixture}/keys`, {})).key;
  // Save the key before record creation: a later error must not lose its only copy.
  await previous?.saveKey?.(key);
  record ||= await request(config.local, token, '/records', { fixture_id: fixture, record_type: type, data_source: 'sensor', ...(type === 'calibration' ? { confirm_empty: true } : {}) });
  return { key, record };
}
export function verifyStoredPoint({ apiRecord, dbRecord, frontendRecord, fixture, recordId, previousIds }) {
  if ([apiRecord, dbRecord, frontendRecord].some(r => r?.record_id !== recordId || r.fixture_id !== fixture || r.data_source !== 'sensor')) throw Error('The API, Supabase and website do not identify the same physical recording.');
  const point = apiRecord.measurements.findLast(p => !previousIds.has(p.reading_id));
  if (!point) return null;
  for (const record of [dbRecord, frontendRecord]) {
    const stored = record.measurements.find(p => p.reading_id === point.reading_id);
    if (!isDeepStrictEqual(stored, point)) throw Error('A new sensor point does not match between API, Supabase and website.');
  }
  return point;
}
